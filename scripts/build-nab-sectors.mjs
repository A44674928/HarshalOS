/* Deterministic, offline digitization. The Compendium owns NAB semantics;
   the TSV owns editorial stock proxies, never provider authorization. */
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const source = 'docs/harshal-systems/14-nab-compendium.md';
const choices = read('docs/models/nab-ticker-assignments.tsv').trim().split('\n').slice(1).map(line => line.split('\t'));
assert.equal(choices.length, 119);
assert.equal(new Set(choices.map(row => row[1])).size, 119, 'Each NAB has a distinct stock proxy');
const records = read(source).split('\n').filter(line => /^\| \d+ \|/.test(line)).slice(0, 119).map((line, index) => {
  const columns = line.split('|').slice(1, -1).map(value => value.trim().replaceAll('**', ''));
  const [id, symbol, name, riskProfile, alignment, legend, trait, authorityDensity, failureMode, roles] = columns;
  const [choiceId, ticker, company, theme, rationale] = choices[index];
  assert.equal(Number(id), index + 1);
  assert.equal(choiceId, id);
  assert.match(ticker, /^[A-Z][A-Z0-9.]{0,9}$/);
  assert.ok(company && theme && rationale && roles);
  const riskLevel = riskProfile.includes('Extreme') ? 3 : riskProfile.includes('Elevated') ? 2 : riskProfile.includes('Moderate') ? 1 : 0;
  return { id: Number(id), symbol, name, riskProfile, riskLevel, alignment, legend, trait, authorityDensity, failureMode, roles,
    ticker, company, theme, rationale, source, mappingStatus: 'editorial-proxy; listing and provider availability unverified',
    operatingBoundary: riskLevel === 3 ? 'reference-only; no NAB deployment' : riskLevel === 1 ? 'sandboxed modeling; no action authority' : 'display-only design context; no action authority' };
});
assert.equal(records.length, 119);
const output = `/* Generated by scripts/build-nab-sectors.mjs; edit the Compendium or assignment TSV, not this file. */
"use strict";
(() => {
  const VERSION = "nab-sectors-v1";
  const sectors = Object.freeze(${JSON.stringify(records, null, 2)}.map(Object.freeze));
  const byId = id => Number.isInteger(id) && id >= 1 && id <= 119 ? sectors[id - 1] : null;
  const byTicker = ticker => typeof ticker === "string" ? sectors.find(row => row.ticker === ticker.toUpperCase()) || null : null;
  function aiContext(id) {
    const row = byId(id);
    if (!row) return null;
    return Object.freeze({
      version: VERSION, nabId: row.id, ticker: row.ticker, theme: row.theme,
      role: row.roles, trait: row.trait, failureMode: row.failureMode,
      boundary: row.operatingBoundary, runtimeStatus: "design-only; no neural network instantiated",
      instructions: "Keep NAB " + row.id + " (" + row.name + ") on theme: " + row.theme +
        ". Use only " + row.ticker + " as its stock proxy. Preserve the role: " + row.roles +
        ". Monitor the documented failure mode: " + row.failureMode +
        ". Boundary: " + row.operatingBoundary +
        ". NAB risk is not investment risk, material safety, or an execution permission. Do not infer missing market or physical data."
    });
  }
  function designation(id) {
    const row = byId(id);
    return row ? Object.freeze({ version: VERSION, nabId: row.id, sector: row, ai: aiContext(id) }) : null;
  }
  Object.defineProperty(globalThis, "NabSectors", { configurable: true, value: Object.freeze({ VERSION, sectors, byId, byTicker, aiContext, designation }) });
})();
`;
const destination = new URL('js/nab-sectors.js', root);
if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), output, 'Run node scripts/build-nab-sectors.mjs');
else writeFileSync(destination, output);
